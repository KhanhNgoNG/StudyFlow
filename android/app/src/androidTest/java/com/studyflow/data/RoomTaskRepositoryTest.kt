package com.studyflow.data

import android.content.Context
import androidx.room.Room
import androidx.room.withTransaction
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import com.studyflow.data.local.database.StudyFlowDatabase
import com.studyflow.data.local.entity.TaskEntity
import com.studyflow.data.repository.RoomTaskRepository
import com.studyflow.data.repository.TaskStorageException
import com.studyflow.data.repository.TaskWriteResult
import com.studyflow.domain.model.*
import java.time.LocalDate
import java.util.UUID
import kotlinx.coroutines.*
import kotlinx.coroutines.channels.Channel
import kotlinx.coroutines.flow.*
import org.junit.After
import org.junit.Assert.*
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith

@RunWith(AndroidJUnit4::class)
class RoomTaskRepositoryTest {
    private val context: Context = ApplicationProvider.getApplicationContext()
    private lateinit var db: StudyFlowDatabase
    private lateinit var repo: RoomTaskRepository
    private val files = mutableListOf<String>()
    private var clock = 1_000L
    private val content = TaskContent("SQL", "Mô tả", SubjectCode.DATABASE,
        LocalDate.of(2026, 10, 28), TaskPriority.HIGH)

    @Before fun setUp() {
        db = Room.inMemoryDatabaseBuilder(context, StudyFlowDatabase::class.java).build()
        repo = RoomTaskRepository(db) { ++clock }
    }
    @After fun tearDown() {
        db.close()
        // Every name is generated by this test; the application's studyflow.db is never touched.
        files.forEach { name ->
            check(name.startsWith("studyflow-test-"))
            context.deleteDatabase(name)
        }
    }

    @Test fun newDatabaseIsEmptyAndCreateRoundTripsDefaults() = runBlocking {
        assertTrue(withTimeout(5_000) { repo.observeActiveTasks().first() }.isEmpty())
        val result = repo.create(content.copy(title = "  SQL  ", dueDate = null))
        assertEquals(result.id, UUID.fromString(result.id).toString())
        val stored = requireNotNull(repo.getStoredTask(result.id))
        assertEquals("SQL", stored.task.title)
        assertNull(stored.task.dueDate)
        assertFalse(stored.task.isCompleted)
        assertFalse(stored.task.isDeleted)
        assertEquals(0L, stored.baseVersion)
        assertEquals(1L, stored.localRevision)
        assertEquals(1_001L, stored.localUpdatedAt)
        assertEquals(LocalSyncState.PENDING, stored.syncState)
        assertEquals(stored, withTimeout(5_000) { repo.observeTask(result.id).first() })
    }

    @Test fun liveListAndDetailFlowsEmitEveryBusinessChange() = runBlocking {
        val listEvents = Channel<List<LocalTask>>(Channel.UNLIMITED)
        val listJob = launch(start = CoroutineStart.UNDISPATCHED) {
            repo.observeActiveTasks().collect { listEvents.send(it) }
        }
        val detailEvents = Channel<LocalTask?>(Channel.UNLIMITED)
        var detailJob: Job? = null
        try {
            assertTrue(listEvents.next { it.isEmpty() }.isEmpty())
            val id = repo.create(content).id
            assertEquals(id, listEvents.next { it.size == 1 }.single().task.id)
            detailJob = launch(start = CoroutineStart.UNDISPATCHED) {
                repo.observeTask(id).collect { detailEvents.send(it) }
            }
            assertEquals("SQL", detailEvents.next { it != null }?.task?.title)
            repo.updateContent(id, content.copy(title = "Mobile"))
            assertEquals("Mobile", listEvents.next { it.singleOrNull()?.task?.title == "Mobile" }.single().task.title)
            assertEquals("Mobile", detailEvents.next { it?.task?.title == "Mobile" }?.task?.title)
            repo.setCompleted(id, true)
            assertTrue(listEvents.next { it.singleOrNull()?.task?.isCompleted == true }.single().task.isCompleted)
            assertTrue(requireNotNull(detailEvents.next { it?.task?.isCompleted == true }).task.isCompleted)
            repo.softDelete(id)
            assertTrue(listEvents.next { it.isEmpty() }.isEmpty())
            assertNull(detailEvents.next { it == null })
        } finally {
            listJob.cancelAndJoin()
            detailJob?.cancelAndJoin()
            listEvents.close()
            detailEvents.close()
        }
    }

    @Test fun enumNamesAndCalendarDatesAreStoredWithoutTimezoneOrOrdinals() = runBlocking {
        for (subject in SubjectCode.entries) for (priority in TaskPriority.entries) {
            val id = repo.create(content.copy(subjectCode = subject, priority = priority)).id
            val row = requireNotNull(repo.getStoredTask(id))
            assertEquals(subject, row.task.subjectCode)
            assertEquals(priority, row.task.priority)
            assertEquals(content.dueDate, row.task.dueDate)
            withContext(Dispatchers.IO) {
                db.openHelper.readableDatabase.query(
                    "SELECT subjectCode, priority, dueDate, syncState FROM tasks WHERE id = ?", arrayOf(id),
                ).use { cursor ->
                    assertTrue(cursor.moveToFirst())
                    assertEquals(subject.name, cursor.getString(0))
                    assertEquals(priority.name, cursor.getString(1))
                    assertEquals("2026-10-28", cursor.getString(2))
                    assertEquals("PENDING", cursor.getString(3))
                }
            }
            repo.updateContent(id, content.copy(subjectCode = subject, priority = priority, dueDate = null))
            assertNull(repo.getStoredTask(id)?.task?.dueDate)
        }
    }

    @Test fun editingPreservesIdentityBaseVersionCompletionAndIncrementsOnlyOnChange() = runBlocking {
        db.taskDao().insert(TaskEntity("server-fixture", "SQL", "Mô tả", SubjectCode.DATABASE,
            content.dueDate, TaskPriority.HIGH, true, false, 42, 7, 500, LocalSyncState.SYNCED))
        val initial = requireNotNull(repo.getStoredTask("server-fixture"))
        assertEquals(TaskWriteResult.Success("server-fixture", false),
            repo.updateContent("server-fixture", content.copy(title = " SQL ")))
        assertEquals(TaskWriteResult.Success("server-fixture", false), repo.setCompleted("server-fixture", true))
        assertEquals(initial, repo.getStoredTask("server-fixture"))
        assertEquals(TaskWriteResult.Success("server-fixture", true),
            repo.updateContent("server-fixture", content.copy(title = "Mobile")))
        val changed = requireNotNull(repo.getStoredTask("server-fixture"))
        assertEquals("server-fixture", changed.task.id)
        assertEquals(42L, changed.baseVersion)
        assertEquals(8L, changed.localRevision)
        assertTrue(changed.task.isCompleted)
        assertEquals(LocalSyncState.PENDING, changed.syncState)
        assertNotEquals(initial.localUpdatedAt, changed.localUpdatedAt)
    }

    @Test fun formDoesNotOverwriteConcurrentCompletionOrResurrectTombstones() = runBlocking {
        val id = repo.create(content).id
        val oldForm = TaskContent.from(requireNotNull(repo.getStoredTask(id)).task)
        repo.setCompleted(id, true)
        repo.updateContent(id, oldForm.copy(title = "Edited"))
        val edited = requireNotNull(repo.getStoredTask(id))
        assertTrue(edited.task.isCompleted)
        assertEquals(3L, edited.localRevision)
        repo.softDelete(id)
        val deleted = requireNotNull(repo.getStoredTask(id))
        assertTrue(deleted.task.isDeleted)
        assertEquals(4L, deleted.localRevision)
        assertEquals(TaskWriteResult.Unavailable, repo.updateContent(id, oldForm))
        assertEquals(TaskWriteResult.Unavailable, repo.setCompleted(id, false))
        assertEquals(TaskWriteResult.Unavailable, repo.toggleCompleted(id))
        assertEquals(TaskWriteResult.Unavailable, repo.softDelete(id))
        assertEquals(deleted, repo.getStoredTask(id))
        assertTrue(withTimeout(5_000) { repo.observeActiveTasks().first() }.isEmpty())
    }

    @Test fun missingIdsNeverCreateRecords() = runBlocking {
        assertNull(repo.getStoredTask("missing"))
        assertEquals(TaskWriteResult.Unavailable, repo.updateContent("missing", content))
        assertEquals(TaskWriteResult.Unavailable, repo.setCompleted("missing", true))
        assertEquals(TaskWriteResult.Unavailable, repo.toggleCompleted("missing"))
        assertEquals(TaskWriteResult.Unavailable, repo.softDelete("missing"))
        assertNull(withTimeout(5_000) { repo.observeTask("missing").first() })
        assertTrue(withTimeout(5_000) { repo.observeActiveTasks().first() }.isEmpty())
    }

    @Test fun concurrentWritesCannotLoseRevisionIncrements() = runBlocking {
        val id = repo.create(content).id
        coroutineScope { repeat(20) { launch(Dispatchers.Default) { repo.toggleCompleted(id) } } }
        val stored = requireNotNull(repo.getStoredTask(id))
        assertEquals(21L, stored.localRevision)
        assertFalse(stored.task.isCompleted)
        assertEquals(0L, stored.baseVersion)
        assertEquals(LocalSyncState.PENDING, stored.syncState)
    }

    @Test fun databaseWriteFailureIsReportedAndRollsBackTaskAndMetadata() = runBlocking {
        val id = repo.create(content).id
        val before = repo.getStoredTask(id)
        withContext(Dispatchers.IO) {
            db.openHelper.writableDatabase.execSQL("""
                CREATE TRIGGER reject_task_update BEFORE UPDATE ON tasks
                BEGIN SELECT RAISE(ABORT, 'test write failure'); END
            """.trimIndent())
        }
        try {
            repo.updateContent(id, content.copy(title = "Must fail"))
            fail("Expected a storage failure")
        } catch (expected: TaskStorageException) {
            assertNotNull(expected.cause)
        }
        assertEquals(before, repo.getStoredTask(id))
    }

    @Test fun outerTransactionRollbackLeavesNoPartialPendingState() = runBlocking {
        val id = repo.create(content).id
        val before = repo.getStoredTask(id)
        class Abort : RuntimeException()
        try {
            db.withTransaction {
                repo.setCompleted(id, true)
                throw Abort()
            }
        } catch (_: Abort) { /* Deliberate rollback, not a repository error. */ }
        assertEquals(before, repo.getStoredTask(id))
    }

    @Test fun databaseReadFailureIsNotAnEmptySuccessfulResult() = runBlocking {
        // Corrupt only this test's in-memory schema, never the application's database file.
        withContext(Dispatchers.IO) { db.openHelper.writableDatabase.execSQL("DROP TABLE tasks") }
        try {
            withTimeout(5_000) { repo.observeActiveTasks().first() }
            fail("A failed query must surface as an error")
        } catch (expected: TaskStorageException) {
            assertNotNull(expected.cause)
        }
    }

    @Test fun fileDatabaseReopenPreservesBusinessDataMetadataAndTombstones() = runBlocking {
        db.close()
        val name = "studyflow-test-${UUID.randomUUID()}.db"
        files += name
        db = Room.databaseBuilder(context, StudyFlowDatabase::class.java, name).build()
        repo = RoomTaskRepository(db) { ++clock }
        val activeId = repo.create(content).id
        val deletedId = repo.create(content.copy(title = "Deleted", dueDate = null)).id
        repo.setCompleted(activeId, true)
        repo.updateContent(activeId, content.copy(title = "Persisted"))
        repo.softDelete(deletedId)
        val activeBefore = repo.getStoredTask(activeId)
        val deletedBefore = repo.getStoredTask(deletedId)
        db.close()
        db = Room.databaseBuilder(context, StudyFlowDatabase::class.java, name).build()
        repo = RoomTaskRepository(db)
        assertEquals(activeBefore, repo.getStoredTask(activeId))
        assertEquals(deletedBefore, repo.getStoredTask(deletedId))
        assertEquals(listOf(activeId), withTimeout(5_000) { repo.observeActiveTasks().first() }.map { it.task.id })
        // All-deleted is a legitimate empty database view and must never trigger sample seeding.
        repo.softDelete(activeId)
        db.close()
        db = Room.databaseBuilder(context, StudyFlowDatabase::class.java, name).build()
        repo = RoomTaskRepository(db)
        assertTrue(withTimeout(5_000) { repo.observeActiveTasks().first() }.isEmpty())
        assertTrue(requireNotNull(repo.getStoredTask(activeId)).task.isDeleted)
        assertEquals(deletedBefore, repo.getStoredTask(deletedId))
    }

    @Test fun storedFlowIncludesPendingTombstonesWhileActiveFlowHidesThem() = runBlocking {
        val deleted = repo.create(content).id
        val active = repo.create(content.copy(title = "Active")).id
        repo.softDelete(deleted)
        val stored = withTimeout(5_000) { repo.observeStoredTasks().first() }
        assertEquals(setOf(deleted, active), stored.map { it.task.id }.toSet())
        assertEquals(2, stored.count { it.syncState == LocalSyncState.PENDING })
        assertEquals(1, stored.count { it.task.isDeleted && it.syncState == LocalSyncState.PENDING })
        assertEquals(listOf(active), withTimeout(5_000) { repo.observeActiveTasks().first() }.map { it.task.id })
    }

    private suspend fun <T> Channel<T>.next(predicate: (T) -> Boolean): T = withTimeout(5_000) {
        var event = receive()
        while (!predicate(event)) event = receive()
        event
    }
}
